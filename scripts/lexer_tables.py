"""Generate the Lean token vocabulary from the executable oracle's Menhir/ocamllex sources."""
import argparse
import os
from pathlib import Path
import re

from source_contract import ORACLE, ROOT, git

FRONT = "src/ml/libvellvm/"
OUTPUT = ROOT / "Vellvm/Frontend/Token.lean"


def without_comments(text):
    # Menhir's token declarations include nested OCaml comments.
    depth = 0
    parts = []
    for piece in re.split(r"(\(\*|\*\))", text):
        if piece == "(*":
            depth += 1
        elif piece == "*)":
            depth -= 1
            if depth < 0:
                raise ValueError("unmatched comment terminator")
        elif depth == 0:
            parts.append(piece)
    if depth:
        raise ValueError("unterminated comment")
    return "".join(parts)


def generate(repo):
    parser = git(repo, "show", f"{ORACLE}:{FRONT}llvm_parser.mly").decode()
    lexer = git(repo, "show", f"{ORACLE}:{FRONT}llvm_lexer.mll").decode()
    notice = parser[parser.index("Copyright (c)"):parser.index("* }}}")]
    header = "\n".join(line.strip("* ") for line in notice.splitlines()).strip()
    token_decls = without_comments(parser.split("%}", 1)[1].split("%%", 1)[0])
    types = {"Parse_util.lexed_id": "(id : LexedId)", "string": "(text : IRString)",
             "LLVMAst.int_syntax": "(value : int_syntax)", "LLVMAst.float_syntax": "(value : float_syntax)",
             "Camlcoq.P.t": "(width : Positive)", "Camlcoq.Z.t": "(id : Int)",
             "(string * string)": "(di body : IRString)"}
    fixed, payloads = [], {}
    for ty, names in re.findall(r"^%token\s*(?:<([^>]+)>\s*)?([^\n]+)", token_decls, re.M):
        for name in names.split():
            if not re.fullmatch("[A-Z][A-Z0-9_]*", name) or name in fixed or name in payloads:
                raise ValueError(f"bad or duplicate token: {name}")
            if ty:
                payloads[name] = types[ty]
            else:
                fixed.append(name)
    words = without_comments(lexer.split("let reserved_words = [", 1)[1].split("\n]", 1)[0])
    keywords = re.findall(r'\("([\w-]+)"\s*,\s*(\w+)\);', words)
    colon_defs = lexer.split("let create_label_or_colon_kw str", 1)[1].split("| _", 1)[0]
    colon = re.findall(r'\| "(\w+)" -> (\w+)', colon_defs)
    if not fixed or not payloads or not keywords or not colon:
        raise ValueError("empty token inventory")
    if words.count(";") != len(keywords):
        raise ValueError("unrecognized reserved word mapping")
    if {t for _, t in keywords + colon} != {t for t in fixed if t.startswith("KW_")}:
        raise ValueError("keyword tables disagree with parser inventory")
    lines = ["/-", header, "Adapted for use in Vellvm by Steve Zdancewic (c) 2017.",
             "Generated by scripts/lexer_tables.py; do not edit by hand.", "-/", "module", "",
             "public import Vellvm.Syntax.LLVMAst", "", "@[expose] public section",
             "namespace Vellvm.Frontend", "open Vellvm.Syntax.LLVMAst", "",
             "inductive LexedId where", "  | Anonymous (id : Nat)", "  | Named (name : IRString)", "",
             "inductive FixedToken where", *("  | " + t for t in fixed), "  deriving BEq, Inhabited", "",
             "inductive Token where", "  | fixed (kind : FixedToken)",
             *(f"  | {t} {p}" for t, p in payloads.items()), "  deriving Inhabited"]
    lines.extend(["", "structure Position where", "  offset : Nat := 0", "  line : Nat := 1",
                  "  column : Nat := 0", "  deriving BEq, Inhabited", "", "structure LocatedToken where",
                  "  token : Token",
                  "  /-- Menhir sees the last matched lexeme, e.g. the closing quote of a string. -/",
                  "  startPos : Position", "  endPos : Position", "  deriving Inhabited"])
    for name, table in [("keywordTable", keywords), ("colonKeywordTable", colon)]:
        if len(set(s for s, _ in table)) != len(table):
            raise ValueError(f"duplicate spelling in {name}")
        lines.extend(["", f"def {name} : Array (String × FixedToken) := #[",
                      ",\n".join(f'  ("{s}", .{t})' for s, t in sorted(table)) + "]"])
    return "\n".join([*lines, "", "end Vellvm.Frontend", ""])


if __name__ == "__main__":
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--write", action="store_true", help="replace the checked-in generated file")
    args = parser.parse_args()
    data = generate(Path(os.environ.get("VELLVM_SRC", ROOT.parent / "vellvm"))).encode()
    if args.write:
        OUTPUT.parent.mkdir(parents=True, exist_ok=True)
        OUTPUT.write_bytes(data)
    elif OUTPUT.read_bytes() != data:
        raise SystemExit(f"lexer token inventory mismatch: {OUTPUT}")
